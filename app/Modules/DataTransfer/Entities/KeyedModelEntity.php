<?php

namespace App\Modules\DataTransfer\Entities;

use App\Modules\DataTransfer\Import\GroupPlan;
use App\Modules\DataTransfer\Import\ImportContext;
use App\Modules\DataTransfer\Support\ImageFetcher;
use Illuminate\Database\Eloquent\Model;

/**
 * An entity stored as one table row per file row, matched by one stable column (an id or a code).
 * Subclasses give the model, the key, the rules and how validated values become attributes.
 */
abstract class KeyedModelEntity extends DataEntity
{
    /** @return class-string<Model> */
    abstract protected function model(): string;

    /** The file column and table column records are matched by. */
    abstract protected function keyColumn(): string;

    /** Validation rules of one row ($existing: the record it updates). */
    abstract protected function rules(?Model $existing): array;

    /** Model attributes from the validated values. */
    abstract protected function attributes(array $data, ?Model $existing, GroupPlan $plan): array;

    /** Image column => public/ folder, for entities with an image. */
    protected function imageColumns(): array
    {
        return [];
    }

    /** Whether the key is generated by the database (id): then new records leave it empty. */
    protected function keyIsDatabaseId(): bool
    {
        return $this->keyColumn() === 'id';
    }

    public function matchDescription(): string
    {
        return $this->keyIsDatabaseId()
            ? 'Matched by id. Leave id empty to create a record; fill it to update that record.'
            : "Matched by {$this->keyColumn()} (unique).";
    }

    public function validate(GroupPlan $plan, ImportContext $context): void
    {
        $rowNumber = $plan->firstRow();
        $row = $plan->rows[$rowNumber];
        $key = self::value($row, $this->keyColumn());
        $modelClass = $this->model();
        $existing = $key !== null ? $modelClass::query()->where($this->keyColumn(), $key)->first() : null;

        if ($key !== null && ($first = $context->claim($this->key().':key', $key, $rowNumber))) {
            $plan->error($rowNumber, $this->keyColumn(), "Duplicate {$this->keyColumn()} in the file (also on row {$first}).", $key);

            return;
        }

        if ($existing) {
            if (!$context->allowsUpdate()) {
                $plan->error($rowNumber, $this->keyColumn(), "{$this->label()} \"{$key}\" already exists (create-only import).", $key);

                return;
            }
            $plan->action = GroupPlan::UPDATE;
        } else {
            if ($key !== null && $this->keyIsDatabaseId()) {
                $plan->error($rowNumber, 'id', "There is no {$this->label()} with id {$key}. Leave id empty to create one.", $key);

                return;
            }
            if (!$context->allowsCreate()) {
                $plan->error($rowNumber, $this->keyColumn(), $key === null
                    ? "{$this->keyColumn()} is required to update."
                    : "{$this->label()} \"{$key}\" does not exist (update-only import).", (string) $key);

                return;
            }
            $plan->action = GroupPlan::CREATE;
        }

        $data = [];
        foreach ($this->importableColumns() as $column) {
            $data[$column] = self::value($row, $column);
        }

        $validated = $this->check($plan, $rowNumber, $data, $this->rules($existing));

        foreach ($this->imageColumns() as $column => $folder) {
            $value = self::value($row, $column);
            if ($value === null && !$existing && in_array($column, $this->requiredHeaders(), true)) {
                $plan->error($rowNumber, $column, 'An image (URL or existing path) is required for a new record.');
            } elseif ($value !== null && (!$existing || $value !== $this->currentImage($existing, $column)) && ($problem = app(ImageFetcher::class)->check($value))) {
                $plan->error($rowNumber, $column, $problem, $value);
            }
        }

        $plan->identifier = $key ?? '(new)';
        $plan->payload = ['data' => $validated, 'existing_id' => $existing?->getKey()];
        $this->afterValidate($plan, $context, $validated, $existing);
    }

    /** Extra checks (relationships, uniqueness against other rows). */
    protected function afterValidate(GroupPlan $plan, ImportContext $context, array $data, ?Model $existing): void
    {
    }

    public function persist(GroupPlan $plan, ImportContext $context): void
    {
        $modelClass = $this->model();
        $existing = $plan->payload['existing_id'] ? $modelClass::query()->lockForUpdate()->findOrFail($plan->payload['existing_id']) : null;
        $attributes = $this->attributes($plan->payload['data'], $existing, $plan);
        $row = $plan->rows[$plan->firstRow()];
        $downloaded = [];

        try {
            foreach ($this->imageColumns() as $column => $folder) {
                $value = self::value($row, $column);
                if ($value !== null && (!$existing || $value !== $this->currentImage($existing, $column))) {
                    $attributes[$this->imageAttribute($column)] = $downloaded[] = app(ImageFetcher::class)->fetch($value, $folder);
                }
            }

            $model = $existing ?? new $modelClass();
            $model->forceFill($attributes)->save();
            $plan->identifier = (string) $model->getAttribute($this->keyColumn());
        } catch (\Throwable $e) {
            foreach ($downloaded as $path) {
                app(ImageFetcher::class)->discard($path);
            }
            throw $e;
        }
    }

    /** Table column an image column is saved in (image_url → image). */
    protected function imageAttribute(string $column): string
    {
        return 'image';
    }

    protected function currentImage(Model $model, string $column): ?string
    {
        return $model->getAttribute($this->imageAttribute($column));
    }

    /**
     * Only the attributes the file filled: an update never blanks a column because a cell was
     * empty, and a new record gets the column defaults for its empty cells.
     */
    protected static function filled(array $attributes, ?Model $existing): array
    {
        return array_filter($attributes, fn ($v) => $v !== null);
    }
}
